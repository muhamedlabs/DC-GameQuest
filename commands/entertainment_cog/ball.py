def analyze_question(question: str) -> str:
    q = question.lower()

    for keywords, responses in SPECIAL_SCENARIOS.items():
        if any(word in q for word in keywords):
            return random.choice(responses)

    if any(word in q for word in NEGATIVE_KEYWORDS):
        return random.choice(NEGATIVE_RESPONSES)

    if any(word in q for word in POSITIVE_KEYWORDS):
        return random.choice(POSITIVE_RESPONSES)

    if any(word in q for word in NEUTRAL_KEYWORDS):
        return random.choice(NEUTRAL_RESPONSES)

    if q.startswith("не ") or "ли не" in q or "не стоит" in q:
        return random.choice(NEGATIVE_RESPONSES)

    if any(w in q for w in ["или", "либо", "выбрать", "лучше"]):
        return random.choice(POSITIVE_RESPONSES + NEGATIVE_RESPONSES)

    return random.choice(POSITIVE_RESPONSES + NEGATIVE_RESPONSES + NEUTRAL_RESPONSES)


class WarBall(commands.Cog):
    def __init__(self, bot):
        self.bot = bot
        self.embed_color = disnake.Color(int(Embed_Color.lstrip("#"), 16))

    @commands.slash_command(
        name="рация",
        description="Тактический прогноз от командного ИИ"
    )
    async def warball(
        self,
        inter: disnake.ApplicationCommandInteraction,
        вопрос: str = commands.Param(
            name="вопрос",
            description="Напишите вопрос, который вас интересует"
        )
    ):
        await inter.response.defer()

        result = analyze_question(вопрос)
        file = disnake.File(Ball_Gif, filename="ball.gif")

        embed = disnake.Embed(
            title="<:courthouse:1388889492865155153> Командный аналитический центр",
            description=(
                f"> Запрос тактического **прогноза** от командного центра. Получите указания и **оценку** ситуации для принятия решения.\n\n"
                f"<:globalsearch:1400133064029638720> **Запрос до штабу:**\n```{вопрос}```\n"
                f"<:firstline:1387180213225390182> **Тактический отчёт:**\n```{result}```"
            ),
            color=self.embed_color
        )
        embed.set_image(url="attachment://ball.gif")

        await inter.edit_original_response(embed=embed, file=file)
